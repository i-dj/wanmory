// placeIndex 按名字（小写）查地方
var placeIndex = func() map[string]knownPlace {
	idx := map[string]knownPlace{}
	for _, p := range folderPlaceList {
		names := strings.Split(p.names, "|")
		kp := knownPlace{name: names[0], lat: p.lat, lon: p.lon}
		for _, n := range names {
			n = strings.ToLower(strings.TrimSpace(n))
			if _, dup := idx[n]; !dup {
				idx[n] = kp
			}
		}
	}
	return idx
}()
